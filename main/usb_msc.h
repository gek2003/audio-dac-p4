/*
 * usb_msc.h — USB Mass Storage: SD-карта платы как USB-диск для ПК.
 *
 * ESP32-P4 имеет USB OTG High-Speed (порт Type-C «USB» на плате Waveshare,
 * USBD_P/N). Компонент espressif/esp_tinyusb (v3.x) с MSC-классом и
 * SDMMC-бэкендом выдаёт карту ПК как сменный диск.
 *
 * Владение картой (два хозяина над одной FAT-ФС жить не могут):
 *   - по умолчанию карта смонтирована в /sdcard и принадлежит приложению
 *     (браузер «Файлы», декодер file://);
 *   - как только ПК подключил кабель и смонтировал диск — MSC-компонент
 *     сам размонтирует FatFS и отдаёт карту ПК; наш обработчик события
 *     останавливает воспроизведение с file:// (HTTP-источник продолжает
 *     работать);
 *   - при отсоединении/Eject на ПК — карта возвращается: FatFS монтируется
 *     обратно, воспроизведение с file:// возобновляется.
 * Это «на лету» в разумном смысле: без перезагрузки и без вынимания карты.
 * Полностью прозрачного ОДНОВРЕМЕННОГО доступа двух хозяев к одной ФС не
 * существует (расхождение кэшей FAT повреждает данные) — переключение
 * владения единственный надёжный вариант.
 */
#pragma once

#include <stddef.h>
#include <stdbool.h>
#include "esp_err.h"

/* Кому принадлежит карта в данный момент. */
typedef enum {
    USB_MSC_OWNER_APP = 0,   /* смонтирована в /sdcard, приложение владеет */
    USB_MSC_OWNER_HOST = 1,  /* передана ПК (USB-диск) */
    USB_MSC_OWNER_NONE = 2,  /* usb_msc_init() не вызван / не готово */
} usb_msc_owner_t;

typedef struct {
    /* Карта уходит ПК: остановить воспроизведение file:// (если играет). */
    void (*on_take_by_host)(void);
    /* Карта вернулась к приложению: можно возобновить воспроизведение. */
    void (*on_return_to_app)(void);
} usb_msc_callbacks_t;

/* Установка MSC-драйвера и создание хранилища на SD-карте.
 * Требует: sd_card_init() уже выполнен. Монтирует FatFS в /sdcard (владение
 * APP) — браузер «Файлы» и декодер file:// работают сразу.
 * Идемпотентен. */
esp_err_t usb_msc_init(const usb_msc_callbacks_t *cb);

/* Текущий владелец карты. */
usb_msc_owner_t usb_msc_owner(void);

/* Краткая строка статуса для диагностики (RU/EN — вызывающий решает). */
void usb_msc_status_text(char *out, size_t cap);
